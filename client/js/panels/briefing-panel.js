import { api } from '../api.js';
import { escapeHtml } from '../format.js';
export const meta = { id: 'briefing', icon: '▤', title: 'Briefing' };
export function mount(host) {
  let disposed = false;
  host.innerHTML = `<div class="panel"><div class="panel-head"><h2>Briefing</h2><p>A template-composed summary of current fusion output — not generated by a language model; every figure traces to a live entity.</p></div>
    <div class="panel-body" id="brief-body"></div><div class="panel-foot"><button class="btn btn-sm btn-block" id="brief-refresh">Refresh</button></div></div>`;
  const body = host.querySelector('#brief-body');
  async function load() { body.innerHTML = `<div class="loading-row"><span class="spinner"></span>Composing…</div>`;
    try { const r = await api.briefing(); if (disposed) return;
      body.innerHTML = r.sections.map((s) => `<h3 style="font-size:11.5px;color:var(--text-1);margin-bottom:4px;">${escapeHtml(s.title)}</h3><p style="font-size:12.5px;color:var(--text-1);line-height:1.6;margin-bottom:14px;">${escapeHtml(s.text)}</p>`).join('');
    } catch (e) { body.innerHTML = `<p class="list-empty">${escapeHtml(e.message)}</p>`; } }
  host.querySelector('#brief-refresh').addEventListener('click', load); load();
  return () => { disposed = true; };
}
